#define SHIP_TRI_COUNT (SHIP_INDEX_COUNT / 3)

static const int SHIP_ENGINE_TRIS[] = {16, 17, 42, 43};
static const int SHIP_DETAIL_TRIS[] = {3, 4, 11, 12, 35, 41};
static const int SHIP_WINDOW_TRIS[] = {2, 38};

static void paint(uint32_t* colors, const int* tris, size_t count, uint32_t color) {
    for(size_t i = 0; i < count; i++) {
        colors[tris[i]] = color;
    }
}

#define PAINT(colors, tris, color) paint(colors, tris, sizeof(tris) / sizeof(tris[0]), color)

mesh_t* ship_mesh_create(ship_colors_t palette) {
    uint32_t colors[SHIP_TRI_COUNT];

    for(size_t i = 0; i < SHIP_TRI_COUNT; i++) {
        colors[i] = palette.body;
    }

    PAINT(colors, SHIP_ENGINE_TRIS, palette.engine);
    PAINT(colors, SHIP_DETAIL_TRIS, palette.detail);
    PAINT(colors, SHIP_WINDOW_TRIS, palette.window);

    return mesh_create(
        SHIP_VERTS,
        SHIP_VERT_COUNT,
        SHIP_INDICES,
        SHIP_INDEX_COUNT,
        colors
    );
}
