void font_draw(renderer_t* r, int x, int y, const char* text, int scale, uint32_t color) {
    for(; *text; text++, x += 6 * scale) {
        char c = *text;
        int i = (c >= 'A' && c <= 'Z') ? c - 'A' : (c >= '0' && c <= '9') ? c - '0' + 26 : -1;
        if(i < 0) continue; // space and unknown chars are blank
        for(int row = 0; row < 7; row++)
            for(int col = 0; col < 5; col++)
                if(glyphs[i][row] & (0x10 >> col))
                    for(int dy = 0; dy < scale; dy++)
                        for(int dx = 0; dx < scale; dx++)
                            renderer_draw_pixel(r, x + col * scale + dx, y + row * scale + dy, color);
    }
}

int font_width(const char* text, int scale) {
    return (int)strlen(text) * 6 * scale;
}
